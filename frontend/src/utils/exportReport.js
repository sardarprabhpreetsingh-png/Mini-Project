/**
 * Generates and triggers download of a Markdown report of the speech analysis
 */
export function exportReportAsMarkdown(result) {
  if (!result) return;

  const { filename, transcript, analysis, feedback } = result;
  const { score, pacing, fillers, pauses, repetitions, duration_formatted, word_count } = analysis;

  const md = `# SpeakSense Communication Analysis Report

**Audio File:** ${filename || 'Speech Recording'}  
**Analysis Date:** ${new Date().toLocaleDateString()}  
**Overall Clarity Score:** ${score?.score || 0}/100 (${score?.level || 'N/A'} - ${score?.badge || ''})

---

## 1. Speech Performance Metrics

| Metric | Measured Value | Target Benchmark |
| :--- | :--- | :--- |
| **Speaking Speed (WPM)** | ${pacing?.wpm || 0} WPM | 130 - 160 WPM (${pacing?.status || 'N/A'}) |
| **Total Words** | ${word_count || 0} words | - |
| **Duration** | ${duration_formatted || '0s'} | - |
| **Filler Words Detected** | ${fillers?.total_fillers || 0} (${fillers?.filler_ratio_percent || 0}%) | < 2.0% (${fillers?.rating || 'N/A'}) |
| **Pause Count** | ${pauses?.pause_count || 0} pauses | Natural Flow |
| **Average Pause Length** | ${pauses?.avg_pause_duration_sec || 0}s | 0.5s - 1.5s |
| **Consecutive Repetitions** | ${repetitions?.consecutive_repeats_count || 0} | 0 |
| **Vocabulary Diversity** | ${repetitions?.vocabulary_diversity_ratio || 0} | > 0.50 |

### Filler Words Breakdown
${
  Object.keys(fillers?.breakdown || {}).length > 0
    ? Object.entries(fillers.breakdown)
        .map(([word, count]) => `- **"${word}"**: ${count} time(s)`)
        .join('\n') +
      (fillers?.occurrences && fillers.occurrences.length > 0
        ? '\n\n**Detected Snippets:**\n' +
          fillers.occurrences.map((o) => `- "${o.word}": *"...${o.context}..."*`).join('\n')
        : '')
    : '_No filler words detected._'
}

---

## 2. Full Transcript

> "${transcript}"

---

## 3. AI Coaching Feedback (${feedback?.source === 'gemini_ai' ? 'Google Gemini AI' : 'Heuristic Rules Engine'} - ${feedback?.model_used || 'SpeakSense Engine'})

### Executive Summary
${feedback?.summary || 'N/A'}

### Delivery & Pacing Assessment
${feedback?.delivery_assessment || 'N/A'}

### Key Strengths
${(feedback?.strengths || []).map((s) => `- ${s}`).join('\n')}

### Areas for Improvement
${(feedback?.weaknesses || []).map((w) => `- ${w}`).join('\n')}

### Recommended Exercises
${(feedback?.actionable_exercises || [])
  .map((ex, i) => `${i + 1}. **${ex.title}**\n   ${ex.instruction}`)
  .join('\n\n')}

### Phrase Rephrasing Suggestions
${
  (feedback?.rephrasing_suggestions || []).length > 0
    ? feedback.rephrasing_suggestions
        .map(
          (r) =>
            `- **Before:** "${r.original}"\n  **After:** "${r.improved}"\n  *Why:* ${r.reason}`
        )
        .join('\n\n')
    : '_No specific phrases flagged for rephrasing._'
}

---
*Report generated by SpeakSense AI-Powered Communication Coaching*
`;

  const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `SpeakSense_Report_${Date.now()}.md`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
